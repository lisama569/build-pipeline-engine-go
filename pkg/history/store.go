// HardHistoryCap bounds configurable retention so records cannot grow the
// state directory without limit.
const HardHistoryCap = 50

// Store retains bounded per-pipeline run records.
type Store struct {
	root string
}

type envelope struct {
	Pipeline  string          `json:"pipeline"`
	RunID     string          `json:"run_id"`
	Payload   string          `json:"payload"`
	RecordRaw json.RawMessage `json:"record"`
}

// Open initializes (if needed) the history directory under stateDir.
func Open(stateDir string) (*Store, error) {
	if stateDir == "" {
		return &Store{}, nil
	}
	dir := filepath.Join(stateDir, "history")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, pipeline.NewError(pipeline.ErrConfigInvalid,
			"cannot create state dir %q: %v", stateDir, err)
	}
	return &Store{root: dir}, nil
}

// Enabled reports whether records are persisted.
func (s *Store) Enabled() bool { return s != nil && s.root != "" }

func (s *Store) dir(pipelineName string) string {
	return filepath.Join(s.root, resume.EscapeName(pipelineName))
}

func recordFile(pipelineDir, runID string) string {
	return filepath.Join(pipelineDir, sanitizeRunID(runID)+".json")
}

// sanitizeRunID keeps run ids file-system safe even if a caller supplies a
// custom id outside the timestamp-hex format generated by resume.NewRunID.
func sanitizeRunID(runID string) string {
	var b strings.Builder
	for _, r := range runID {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9',
			r == '-', r == '_', r == '.', r == 'T':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	if b.Len() == 0 {
		return "run"
	}
	return b.String()
}

// Save writes one record atomically (unique per run id) and prunes retention.
// Different pipelines use different directories; same-pipeline concurrent
// writers use different run-id file names, so records never overwrite each
// other. Retention pruning only ever deletes files older than the surviving
// set by start time; ties are broken deterministically by run id.
func (s *Store) Save(rec *Record, retain int) error {
	if !s.Enabled() {
		return nil
	}
	if rec == nil || rec.Pipeline == "" || rec.RunID == "" {
		return pipeline.NewError(pipeline.ErrConfigInvalid, "refusing to save empty history record")
	}
	if retain < 0 {
		retain = 0
	}
	if retain > HardHistoryCap {
		retain = HardHistoryCap
	}
	if retain == 0 {
		// History disabled: write nothing. Existing retained records are left
		// untouched (disabling retention is not an order to delete history).
		return nil
	}

	raw, err := json.Marshal(rec)
	if err != nil {
		return fmt.Errorf("history encode: %w", err)
	}
	checksum := sha256.Sum256(raw)
	env, err := json.MarshalIndent(&envelope{
		Pipeline: rec.Pipeline, RunID: rec.RunID,
		Payload: hex.EncodeToString(checksum[:]), RecordRaw: raw,
	}, "", "  ")
	if err != nil {
		return err
	}

	pdir := s.dir(rec.Pipeline)
	if err := os.MkdirAll(pdir, 0o755); err != nil {
		return err
	}
	final := recordFile(pdir, rec.RunID)
	tmp, err := os.CreateTemp(pdir, ".tmp-*")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	cleanup := func() { _ = os.Remove(tmpName) }
	if _, err := tmp.Write(env); err != nil {
		tmp.Close()
		cleanup()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		cleanup()
		return err
	}
	if err := tmp.Close(); err != nil {
		cleanup()
		return err
	}
	if err := os.Rename(tmpName, final); err != nil {
		cleanup()
		return err
	}
	return s.prune(rec.Pipeline, retain)
}

// List returns retained records for a pipeline, newest first.
// Corrupt/unreadable records are skipped (and quarantined) rather than
// failing the listing.
func (s *Store) List(pipelineName string) ([]*Record, error) {
	if !s.Enabled() {
		return nil, nil
	}
	entries, err := os.ReadDir(s.dir(pipelineName))
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var recs []*Record
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".json") {
			continue
		}
		rec, err := s.readFile(filepath.Join(s.dir(pipelineName), e.Name()))
		if err != nil {
			// quarantine corrupt files; they never participate in listings.
			if pe := pipeline.AsError(err); pe != nil && pe.Code == pipeline.ErrStateCorrupt {
				_ = os.Rename(filepath.Join(s.dir(pipelineName), e.Name()),
					filepath.Join(s.dir(pipelineName), e.Name()+".bad"))
				continue
			}
			return nil, err
		}
		recs = append(recs, rec)
	}
	sort.Slice(recs, func(i, j int) bool {
		if !recs[i].StartedAt.Equal(recs[j].StartedAt) {
			return recs[i].StartedAt.After(recs[j].StartedAt)
		}
		return recs[i].RunID > recs[j].RunID
	})
	return recs, nil
}

// Load fetches one record by run id.
func (s *Store) Load(pipelineName, runID string) (*Record, error) {
	if !s.Enabled() {
		return nil, nil
	}
	rec, err := s.readFile(recordFile(s.dir(pipelineName), runID))
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	return rec, err
}

// Latest returns the most recent retained record, or nil.
func (s *Store) Latest(pipelineName string) (*Record, error) {
	recs, err := s.List(pipelineName)
	if err != nil || len(recs) == 0 {
		return nil, err
	}
	return recs[0], nil
}

func (s *Store) readFile(path string) (*Record, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var env envelope
	if err := json.Unmarshal(data, &env); err != nil {
		return nil, pipeline.NewError(pipeline.ErrStateCorrupt,
			"%s: cannot decode: %v", filepath.Base(path), err)
	}
	var compact bytes.Buffer
	if err := json.Compact(&compact, env.RecordRaw); err != nil {
		return nil, pipeline.NewError(pipeline.ErrStateCorrupt,
			"%s: invalid embedded JSON", filepath.Base(path))
	}
	checksum := sha256.Sum256(compact.Bytes())
	if hex.EncodeToString(checksum[:]) != env.Payload {
		return nil, pipeline.NewError(pipeline.ErrStateCorrupt,
			"%s: checksum mismatch", filepath.Base(path))
	}
	var rec Record
	if err := json.Unmarshal(env.RecordRaw, &rec); err != nil {
		return nil, pipeline.NewError(pipeline.ErrStateCorrupt,
			"%s: invalid payload", filepath.Base(path))
	}
	if rec.RunID != env.RunID || rec.Pipeline != env.Pipeline {
		return nil, pipeline.NewError(pipeline.ErrStateCorrupt,
			"%s: envelope/payload identity mismatch", filepath.Base(path))
	}
	return &rec, nil
}

// prune keeps only the newest retain records for a pipeline. It sorts by
// StartedAt (newest first, run id tie-break) and deletes the remainder.
func (s *Store) prune(pipelineName string, retain int) error {
	pdir := s.dir(pipelineName)
	entries, err := os.ReadDir(pdir)
	if err != nil {
		return err
	}
	type file struct {
		name string
		rec  *Record
	}
	var good []file
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".json") {
			continue
		}
		path := filepath.Join(pdir, e.Name())
		rec, err := s.readFile(path)
		if err != nil {
			if pe := pipeline.AsError(err); pe != nil && pe.Code == pipeline.ErrStateCorrupt {
				_ = os.Rename(path, path+".bad")
				continue
			}
			return err
		}
		good = append(good, file{e.Name(), rec})
	}
	sort.Slice(good, func(i, j int) bool {
		if !good[i].rec.StartedAt.Equal(good[j].rec.StartedAt) {
			return good[i].rec.StartedAt.After(good[j].rec.StartedAt)
		}
		return good[i].rec.RunID > good[j].rec.RunID
	})
	for i := retain; i < len(good); i++ {
		if err := os.Remove(filepath.Join(pdir, good[i].name)); err != nil {
			return err
		}
	}
	return nil
}

// FromResults builds a Record from a completed run.
func FromResults(pipelineName, runID, parentRunID string,
	startedAt time.Time, stopReason pipeline.StopReason, runStatus, conclusion string,
	tasks []*pipeline.Task, results map[string]pipeline.TaskResult,
	reused, cached int) *Record {
	rec := &Record{
		Pipeline: pipelineName, RunID: runID, ParentRunID: parentRunID,
		StartedAt: startedAt, EndedAt: time.Now(),
		StopReason: stopReason, RunStatus: runStatus, Conclusion: conclusion,
		ReusedCount: reused, CachedCount: cached,
	}
	rec.Duration = rec.EndedAt.Sub(startedAt)
	for _, t := range tasks {
		r, ok := results[t.ID]
		if !ok {
			continue
		}
		if !r.Reused && !r.Cached {
			rec.ReranCount++
		}
		rec.Tasks = append(rec.Tasks, TaskRecord{
			ID: t.ID, Status: r.Status, Reason: r.Reason, Attempts: r.Attempts,
			Cached: r.Cached, Reused: r.Reused, RerunReason: r.RerunReason,
			OutputDigest: r.Output.Digest,
		})
	}
	return rec
}
